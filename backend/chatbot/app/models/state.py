from typing import List, Dict, Any, Optional, Literal
from pydantic import BaseModel, Field
from chatbot.config.settings import settings


class AgentState(BaseModel):
    """Central state passed across all nodes in the Text-to-SQL agent graph."""

    # 1. Inputs & Conversation Memory
    user_input: str = Field(description="Raw user input or question")
    history: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Previous turns containing question, SQL, and query results",
    )

    # 2. Query Understanding & Classification Outputs
    intent: Optional[Literal["greeting", "answer_from_memory", "database_query", "out_of_scope"]] = Field(
        default=None,
        description="Classified user intent: greeting, answer_from_memory, database_query, or out_of_scope",
    )
    is_follow_up: bool = Field(
        default=False,
        description="Flag indicating if the query references or depends on previous turns",
    )
    processed_query: Optional[str] = Field(
        default=None,
        description="Rewritten standalone query (incorporating context) or original query as-is",
    )
    direct_response: Optional[str] = Field(
        default=None,
        description="Direct answer if intent is 'greeting', 'answer_from_memory', or 'out_of_scope'",
    )
    query_variations: List[str] = Field(
        default_factory=list,
        description="List of 3 pruned, keyword-dense search variations generated by LLM",
    )
    search_queries: List[str] = Field(
        default_factory=list,
        description="All queries executed across multi-index stores: original query + 3 variations",
    )

    # 3. Retrieved Knowledge & Schema Context
    retrieved_examples: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Few-shot question-SQL pairs retrieved from ChromaDB",
    )
    retrieved_rules: List[str] = Field(
        default_factory=list,
        description="Business rules and domain definitions retrieved from ChromaDB",
    )
    is_context_sufficient: bool = Field(
        default=False,
        description="Whether retrieved context is sufficient for SQL generation",
    )
    context_assessment_status: Optional[str] = Field(
        default=None,
        description="One of: 'sufficient', 'needs_targeted_retrieval', 'ambiguous', 'out_of_scope'",
    )
    clarification_question: Optional[str] = Field(
        default=None,
        description="Clarifying question to ask the user if query has multiple conflicting interpretations",
    )
    clarification_options: Optional[List[str]] = Field(
        default_factory=list,
        description="List of clarification options/choices presented to the user",
    )
    re_retrieval_count: int = Field(
        default=0,
        description="Number of targeted re-retrieval attempts executed (max 1)",
    )
    schema_context: Dict[str, Any] = Field(
        default_factory=dict,
        description="Explored schema information (tables, columns, foreign keys)",
    )
    retrieved_tables: List[str] = Field(
        default_factory=list,
        description="List of target table names selected and expanded by retriever",
    )
    value_hints: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Extracted database literal matches, enums, and column conditions",
    )

    # 4. SQL Generation & Repair Execution
    sql_query: Optional[str] = Field(
        default=None,
        description="Generated executable MySQL query",
    )
    sql_results: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Rows returned from database execution",
    )
    error: Optional[str] = Field(
        default=None,
        description="Error message if SQL execution or validation failed",
    )
    retry_count: int = Field(
        default=0,
        description="Number of repair attempts performed so far",
    )
    max_retries: int = Field(
        default_factory=lambda: settings.MAX_SQL_RETRIES,
        description="Maximum allowed self-correction repair attempts",
    )

    # 5. Final Output
    final_answer: Optional[str] = Field(
        default=None,
        description="Final natural language response formatted with business context",
    )
